#include <iostream>
using namespace std;
int main() {
   
    // number 15 into diff number system 

    int decimal = 15 ; // decimal -- base 10
    int octal = 017 ; // octal -- base 8
    int hexa = 0x0f ; // hexa  -- base 16
    int binary = 0b00001111 ; // binary -- base 2

cout << "decimal   " << decimal << endl;
cout << "octal  " << octal << endl;
cout << "hexa  " << hexa << endl;
cout << "binary " << binary << endl;


    return 0;
}